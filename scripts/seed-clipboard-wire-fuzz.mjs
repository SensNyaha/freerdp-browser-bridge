import { mkdir, writeFile } from 'node:fs/promises';
const root = new URL('../build/fuzz/clipboard-wire-corpus/', import.meta.url);
await mkdir(root, { recursive: true });
const samples = [
  '0001000f0010000000000000000000010000000000000002',
  '000100010000000000000000000000010000000000000002',
  '000100020000000000000000000000010000000000000000d096f09f98800a',
  '000100010000000000000000000000010000000000000002d096f09f98800a',
  '000100010001000000000000000000010000000000000002',
  '000100010007000000000000000000010000000000000002',
  '00010002000000000000000000000001000000000000000000',
];
for (let i = 0; i < samples.length; ++i)
  await writeFile(
    new URL('payload-' + i, root),
    Buffer.from(samples[i], 'hex'),
  );
